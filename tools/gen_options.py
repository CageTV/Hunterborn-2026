"""Generate plugin/src/Tables.inc (the page tables of HunterbornNative.dll) from docs/mcm_table.json and docs/globals_map.json.

  python tools/gen_options.py

One Def per interactive option, in the order of the original menu. Options that need hand-written native behaviour (start/stop,
the experience reset menu, the SkyRe/PerMa gatherer toggles) are left out of the tables and drawn by Menu.cpp.
"""
import json
import os
import re
from collections import OrderedDict

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TAB = chr(9)
tbl = json.load(open(os.path.join(HERE, "docs", "mcm_table.json"), encoding="utf-8"))
gmap = json.load(open(os.path.join(HERE, "docs", "globals_map.json"), encoding="utf-8"))
pages = {int(k): v for k, v in tbl["pages"].items()}

# Menu text arrays: string-list properties of the MCM quest (filled in by the plugin, not by the script); $keys are translated.
TRANS = r"C:/Modlists/Tabula/mods/Hunterborn SE MCM/Interface/Translations/Hunterborn_ENGLISH.txt"
tr = {}
for line in open(TRANS, encoding="utf-16").read().splitlines():
    if TAB in line:
        k, v = line.split(TAB, 1)
        tr[k.strip()] = v.strip()
arrays = {}
cur = None
for line in open(os.path.join(HERE, "docs", "mcm_quest_props.yaml"), encoding="utf-8").read().splitlines():
    m = re.match(r"\s*Name:\s*(\w+Strings)\s*$", line)
    if m:
        cur = m.group(1)
        arrays[cur] = []
        continue
    if cur:
        m = re.match(r"\s*-\s+(\S.*)$", line)
        if m and not m.group(1).startswith("MutagenObjectType"):
            arrays[cur].append(tr.get(m.group(1).strip(), m.group(1).strip()))
        elif not re.match(r"\s*(Data:\s*)?$", line):
            cur = None

# Deferred actions applied when the menu closes (bit flags; see Actions.h).
FLAG = {
    "_ToggleSmallGame": "ActSmallGame", "_ToggleCorpDragons": "ActCorpDragons", "_ToggleMonsterHunter": "ActMonsterHunter",
    "_ToggleKnifeSales": "ActKnifeSales", "_ToggleKnife": "ActKnife", "_ToggleConfig": "ActSpellConfig", "_ToggleForaging": "ActSpellForaging",
    "_ToggleScrimshaw": "ActSpellScrimshaw", "_TogglePrimCooking": "ActSpellPrimCooking", "_ToggleSenseDir": "ActSpellSenseDir",
    "_ToggleTracking": "ActSpellTracking", "_ToggleTaxonomy": "ActSpellTaxonomy", "_ToggleBotany": "ActPerkBotany", "_ToggleBounty": "ActPerkBounty",
    "_ToggleSavageArrows": "ActPerkSavage", "_ToggleHideAbilities": "ActHideAbilities", "_TogglePeltValue": "ActInit", "_ToggleMeatValue": "ActInit",
    "_ToggleReweighMeat": "ActInit",
}
SKIP_GLOBALS = {"gHunterbornActive"}
SKIP_LABELS = {"Reset to", "(SkyRe) Remove Gatherer perk", "(PerMa) Remove Gatherer perk"}


def fl(x):
    t = f"{x:.6g}"
    return (t if ("." in t or "e" in t) else t + ".0") + "f"


def cstr(s):
    bs = chr(92)
    return '"' + (s or "").replace(bs, bs + bs).replace('"', bs + '"').replace("\n", " ") + '"'


def num(s, fallback=0.0):
    if s is None:
        return fallback
    s = str(s).strip()
    if s.lower() == "true":
        return 1.0
    if s.lower() == "false":
        return 0.0
    try:
        return float(s)
    except ValueError:
        return fallback


def fmt_of(f):
    """MCM slider format ('{2}', '{0}%', '{0} Hours') -> printf."""
    if not f:
        return "%.0f"
    out = re.sub(r"\{(\d)\}", lambda m: "%." + m.group(1) + "f", f.replace("%", "%%"))
    return out if "%." in out else "%.0f"


# ---- collect per page, de-duplicated by option id, first appearance order ------------------------------------------------------------
per_page = OrderedDict()
seen = {}
for o in tbl["options"]:
    if o["type"] in ("text", "empty"):
        continue
    key = o.get("oid") or (o["type"], o["label"], o["page"])
    if key in seen:
        old = seen[key]
        if len(o) > len(old):
            old.update({k: v for k, v in o.items() if v not in (None, [], "")})
        continue
    seen[key] = o
    per_page.setdefault(o["page"], []).append(o)

out = ["// Generated by tools/gen_options.py from docs/mcm_table.json and docs/globals_map.json. Do not edit by hand.", ""]
menus = []
page_defs = []
key_slot = 0
skipped = []
total = 0
for p in sorted(per_page):
    rows = []
    for o in per_page[p]:
        if o["type"] == "header":
            rows.append(("HEADER", o["label"]))
            continue
        g = o.get("global")
        if o["label"] in SKIP_LABELS or g in SKIP_GLOBALS or not g or g not in gmap:
            skipped.append((pages[p], o["label"], g))
            continue
        info = gmap[g]
        local = int(info["formid"], 16)
        dflt = num(o.get("default"), num(info.get("data"), 0.0))
        tip = o.get("hint", "")
        flags = " | ".join(sorted({FLAG[e.split("=")[0].strip()] for e in o.get("side_effects", []) if e.split("=")[0].strip() in FLAG})) or "0"
        if o["type"] == "toggle":
            rows.append(("TOG", g, o["label"], tip, local, dflt, flags))
        elif o["type"] == "slider":
            rows.append(("SLD", g, o["label"], tip, local, dflt, num(o.get("min")), num(o.get("max"), 1.0), num(o.get("step"), 1.0), fmt_of(o.get("format")), flags))
        elif o["type"] == "menu":
            name = f"kMenu{len(menus)}"
            items = arrays.get(o.get("menu_array")) or ["?"]
            menus.append((name, items))
            rows.append(("CMB", g, o["label"], tip, local, dflt, name, flags))
        elif o["type"] == "keymap":
            rows.append(("KEY", g, o["label"], tip, local, key_slot, flags))
            key_slot += 1
        total += 1
    page_defs.append((pages[p], f"kPage{p}", rows))

for name, items in menus:
    out.append(f"constexpr const char* {name}[] = {{ " + ", ".join(cstr(i) for i in items) + " };")
out.append("")
for title, arr, rows in page_defs:
    out.append(f"constexpr Def {arr}[] = {{")
    for r in rows:
        if r[0] == "HEADER":
            out.append(f"\tHEADER({cstr(r[1])}),")
        elif r[0] == "TOG":
            out.append(f"\tTOG({cstr(r[1])}, {cstr(r[2])}, {cstr(r[3])}, {r[4]:#08x}, {fl(r[5])}, {r[6]}),")
        elif r[0] == "SLD":
            out.append(f"\tSLD({cstr(r[1])}, {cstr(r[2])}, {cstr(r[3])}, {r[4]:#08x}, {fl(r[5])}, {fl(r[6])}, {fl(r[7])}, {fl(r[8])}, {cstr(r[9])}, {r[10]}),")
        elif r[0] == "CMB":
            out.append(f"\tCMB({cstr(r[1])}, {cstr(r[2])}, {cstr(r[3])}, {r[4]:#08x}, {fl(r[5])}, {r[6]}, {r[7]}),")
        elif r[0] == "KEY":
            out.append(f"\tKEY({cstr(r[1])}, {cstr(r[2])}, {cstr(r[3])}, {r[4]:#08x}, {r[5]}),")
    out.append("};")
    out.append("")
out.append(f"inline constexpr int kPageTotal = {len(page_defs)};")
out.append("const Page kPages[kPageTotal] = {")
for title, arr, rows in page_defs:
    out.append(f"\t{{ {cstr(title)}, {arr}, static_cast<int>(std::size({arr})) }},")
out.append("};")
os.makedirs(os.path.join(HERE, "plugin", "src"), exist_ok=True)
open(os.path.join(HERE, "plugin", "src", "Tables.inc"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(f"pages {len(page_defs)}, options {total}, menus {len(menus)}, key slots {key_slot}")
print("skipped:", skipped)

# ---- every global by its script name (for the deferred actions: gMonsterHunter, gSkinLevel ...) ---------------------------------------------------
NL = chr(10)
gl = ["// Generated by tools/gen_options.py from docs/globals_map.json. Do not edit by hand.", "struct GlobalId { const char* name; unsigned id; };", "constexpr GlobalId kGlobals[] = {"]
for name in sorted(gmap):
    gl.append(f'    {{ "{name}", {int(gmap[name]["formid"], 16):#08x} }},')
gl.append("};")
open(os.path.join(HERE, "plugin", "src", "Globals.inc"), "w", encoding="utf-8", newline=NL).write(NL.join(gl) + NL)
print("Globals.inc:", len(gmap), "globals")
