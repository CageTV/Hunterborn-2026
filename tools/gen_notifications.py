"""Extracts what 'Hunterborn - Messages to Notifications' changes, so the DLL can do it natively on SE MCM's own messages.

  python tools/gen_notifications.py <spriggit-export-of-SE-MCM-Hunterborn.esp> <spriggit-export-of-the-patch>

For every Message record that differs: the EditorID, whether the patch drops the MessageBox flag, its DisplayTime, and (for the few that also
change wording) the new text. Writes docs/notifications.json and plugin/src/Notifications.inc.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
base, patch = sys.argv[1], sys.argv[2]
NL = chr(10)


def load(folder):
    out = {}
    d = os.path.join(folder, "Messages")
    for f in os.listdir(d):
        t = open(os.path.join(d, f), encoding="utf-8").read().replace(chr(13), "")
        ed = re.search(r"^EditorID:\s*(\S+)", t, re.M).group(1)
        fk = re.search(r"^FormKey:\s*([0-9A-F]{6}):(\S+)", t, re.M)
        flags = re.findall(r"^- (MessageBox|AutoDisplay)\s*$", t.split("Flags:")[1].split(NL + NL)[0] if "Flags:" in t else "", re.M)
        dt = re.search(r"^DisplayTime:\s*(\d+)", t, re.M)
        desc = re.search(r"^Description:\s*\n\s+(?:TargetLanguage:.*\n\s+)?Value:\s*(.*)$", t, re.M)
        out[ed] = {"local": int(fk.group(1), 16), "msgbox": "MessageBox" in t.split("MenuButtons")[0].split("Flags:")[-1] if "Flags:" in t else False,
                   "time": int(dt.group(1)) if dt else None, "text": desc.group(1).strip() if desc else None, "raw": t}
    return out


b, p = load(base), load(patch)
changed = []
for ed, rp in p.items():
    rb = b.get(ed)
    if not rb or rb["raw"] == rp["raw"]:
        continue
    dropped = rb["msgbox"] and not rp["msgbox"]
    entry = {"id": ed, "local": rb["local"], "drop_box": dropped, "time": rp["time"]}
    if rp["text"] and rb["text"] and rp["text"] != rb["text"]:
        entry["text"] = rp["text"]
    changed.append(entry)
changed.sort(key=lambda e: e["id"].lower())
json.dump(changed, open(os.path.join(HERE, "docs", "notifications.json"), "w", encoding="utf-8"), indent=1)

lines = ["// Generated by tools/gen_notifications.py from the Messages to Notifications patch. Do not edit by hand.",
         "struct NoteDef { const char* id; unsigned local; bool dropBox; int time; const char* text; };", "constexpr NoteDef kNotes[] = {"]
for e in changed:
    t = e.get("text")
    txt = "nullptr" if not t else '"' + t.replace(chr(92), chr(92) * 2).replace('"', chr(92) + '"') + '"'
    lines.append(f'    {{ "{e["id"]}", {e["local"]:#08x}, {"true" if e["drop_box"] else "false"}, {e["time"] if e["time"] else 0}, {txt} }},')
lines.append("};")
open(os.path.join(HERE, "plugin", "src", "Notifications.inc"), "w", encoding="utf-8", newline=NL).write(NL.join(lines) + NL)
print(f"{len(changed)} changed messages: drop box {sum(1 for e in changed if e['drop_box'])}, new text {sum(1 for e in changed if 'text' in e)}")
for e in changed[:6]:
    print("  ", e)
